import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'
import { launchTomada, shot, type Session } from './helpers'
import { DEFAULT_DICTIONARY } from '../../src/shared/dictionary'

let s: Session | undefined
test.afterEach(async () => { if (s) { const problems = s.problems; await s.close(); s = undefined; expect(problems, problems.join('\n')).toEqual([]) } })

test('primeira execução detecta faltas, prepara com progresso e permite seguir sem IA', async () => {
  s = await launchTomada({ env: { TOMADA_TEST_ONBOARDING: '1', TOMADA_TRANSCRIBER: 'mock-unprepared', TOMADA_LLM: 'off', TOMADA_TEST_PREPARE_FAIL: 'packages', TOMADA_TEST_PREPARE_STEP_MS: '300' } })
  const { page } = s
  await expect(page.getByTestId('onboarding-view')).toBeVisible()
  await expect(page.getByTestId('diagnostic-transcription')).toHaveAttribute('data-status', 'missing')
  await expect(page.getByTestId('diagnostic-ai')).toHaveAttribute('data-status', 'missing')
  await expect(page.getByTestId('diagnostic-projects')).toHaveAttribute('data-status', 'ok')
  await expect(page.getByTestId('diagnostic-ffmpeg')).toHaveAttribute('data-status', 'ok')
  await expect(page.getByTestId('onboarding-view')).toContainText('aproximadamente 3 GB')
  await shot(page, 'm5-primeira-execucao-faltas')
  await page.getByTestId('prepare-start').click()
  await expect(page.getByTestId('prepare-progress')).toBeVisible()
  await expect(page.getByTestId('prepare-error')).toBeVisible()
  await page.getByTestId('prepare-retry').click()
  await expect(page.getByTestId('prepare-ready')).toBeVisible()
  await expect(page.getByTestId('diagnostic-transcription')).toHaveAttribute('data-status', 'ok')
  await page.getByTestId('diagnostic-test-permissions').click()
  await expect(page.getByTestId('diagnostic-permissions')).toHaveAttribute('data-status', 'ok')
  await page.getByTestId('diagnostic-without-ai').click()
  await expect(page.getByTestId('diagnostic-ai')).toHaveAttribute('data-status', 'skipped')
  await page.getByTestId('onboarding-done').click()
  await expect(page.getByRole('heading', { name: 'Biblioteca', level: 1 })).toBeVisible()
  const saved = JSON.parse(readFileSync(join(s.userData, 'settings.json'), 'utf8'))
  expect(saved.onboarding.withoutAi).toBe(true)
  expect(saved.onboarding.completedAt).toBeTruthy()
})

test('pular lembra as faltas desta abertura e o guia continua acessível nos Ajustes', async () => {
  s = await launchTomada({ env: { TOMADA_TEST_ONBOARDING: '1', TOMADA_TRANSCRIBER: 'mock-unprepared', TOMADA_LLM: 'off' } })
  await expect(s.page.getByTestId('onboarding-view')).toBeVisible()
  await s.page.getByTestId('onboarding-skip').click()
  await expect(s.page.getByRole('heading', { name: 'Biblioteca', level: 1 })).toBeVisible()
  const base = s.base
  await s.close({ keep: true }); s = undefined
  s = await launchTomada({ base, env: { TOMADA_TEST_ONBOARDING: '1', TOMADA_TRANSCRIBER: 'mock-unprepared', TOMADA_LLM: 'off' } })
  await expect(s.page.getByRole('heading', { name: 'Biblioteca', level: 1 })).toBeVisible()
  await expect(s.page.getByTestId('onboarding-view')).toHaveCount(0)
  await s.page.getByTestId('nav-settings').click()
  await s.page.getByTestId('diagnostics-open').click()
  await expect(s.page.getByTestId('onboarding-view')).toBeVisible()
  await expect(s.page.getByTestId('diagnostic-transcription')).toHaveAttribute('data-status', 'missing')
})

test('ajustes guardam vocabulário, estilos próprios por formato, exportação e atalhos conferidos', async () => {
  s = await launchTomada()
  const { page } = s
  await page.getByTestId('nav-settings').click()
  await expect(page.getByTestId('dictionary-input')).toHaveValue(DEFAULT_DICTIONARY.join('\n'))
  await page.getByTestId('settings-default-style').scrollIntoViewIfNeeded()
  await shot(page, 'm5-ajustes-estilo-inicial')
  await page.getByTestId('default-background-menta').click()
  await page.getByTestId('default-camera-shape').selectOption('rounded')
  await page.getByTestId('default-captions-enabled').check()
  await page.getByTestId('default-caption-words').fill('4')
  await page.getByTestId('default-zoom').selectOption('off')
  await page.getByTestId('default-format-vertical').click()
  await expect(page.getByTestId('default-captions-enabled')).toBeChecked()
  await page.getByTestId('default-captions-enabled').uncheck()
  await page.getByTestId('default-caption-style').selectOption('highlight')
  await page.getByTestId('default-zoom').selectOption('subtle')
  await page.getByTestId('default-style-save').click()
  await expect(page.getByTestId('toast')).toContainText('Estilo guardado')
  await shot(page, 'm5-ajustes-estilo-por-formato')
  await page.getByTestId('default-export-resolution').selectOption('1440p')
  await page.getByTestId('default-export-fps-horizontal').selectOption('60')
  await page.getByTestId('export-defaults-save').click()
  await page.getByTestId('shortcut-recordStop').fill('Ctrl+Alt+R')
  await page.getByTestId('shortcut-pause').fill('Ctrl+Alt+R')
  await page.getByTestId('shortcuts-save').click()
  await expect(page.getByTestId('shortcut-conflict')).toContainText('diferentes')
  await page.getByTestId('shortcut-pause').fill('Ctrl+Alt+P')
  await s.app.evaluate(({ globalShortcut }) => {
    if (!globalShortcut.register('Ctrl+Alt+P', () => undefined)) throw new Error('Não consegui reservar o atalho do teste.')
  })
  await page.getByTestId('shortcuts-save').click()
  await expect(page.getByTestId('shortcut-conflict')).toContainText('outro programa')
  const rejected = JSON.parse(readFileSync(join(s.userData, 'settings.json'), 'utf8'))
  expect(rejected.shortcuts).toBeUndefined()
  expect(await s.app.evaluate(({ globalShortcut }) => globalShortcut.isRegistered('Ctrl+Alt+R'))).toBe(false)
  await s.app.evaluate(({ globalShortcut }) => globalShortcut.unregister('Ctrl+Alt+P'))
  await page.getByTestId('shortcuts-save').click()
  await expect(page.getByTestId('shortcut-conflict')).toHaveCount(0)
  await page.getByTestId('dictionary-input').fill('Sintomax\nTermo pessoal')
  await page.getByTestId('dictionary-save').click()
  await page.getByTestId('transcription-engine').selectOption('whisper-cpp')
  await expect(page.getByRole('status').filter({ hasText: 'Feche e abra o Tomada' })).toBeVisible()
  await page.getByTestId('nav-library').click()
  await page.getByTestId('nav-settings').click()
  await expect(page.getByTestId('default-camera-shape')).toHaveValue('rounded')
  await expect(page.getByTestId('default-caption-words')).toHaveValue('4')
  await expect(page.getByTestId('default-captions-enabled')).toBeChecked()
  await expect(page.getByTestId('default-zoom')).toHaveValue('off')
  await page.getByTestId('default-format-vertical').click()
  await expect(page.getByTestId('default-captions-enabled')).not.toBeChecked()
  await expect(page.getByTestId('default-caption-style')).toHaveValue('highlight')
  await expect(page.getByTestId('default-zoom')).toHaveValue('subtle')
  await expect(page.getByTestId('default-export-resolution')).toHaveValue('1440p')
  await expect(page.getByTestId('shortcut-recordStop')).toHaveValue('Ctrl+Alt+R')
  await expect(page.getByTestId('dictionary-input')).toHaveValue('Sintomax\nTermo pessoal')
  const saved = JSON.parse(readFileSync(join(s.userData, 'settings.json'), 'utf8'))
  expect(saved.ownerCaptionsHorizontal.enabled).toBe(true)
  expect(saved.ownerCaptionsVertical.enabled).toBe(false)
  expect(saved.exportDefaults.horizontal).toEqual({ resolution: '1440p', fps: 60 })
  expect(saved.transcription.engine).toBe('whisper-cpp')
})

test('Gravar restaura uma escolha rejeitada e bloqueia botão e atalho durante erro ou salvamento', async () => {
  s = await launchTomada()
  const { page } = s
  await page.getByTestId('nav-settings').click()
  await page.getByTestId('shortcut-recordStop').fill('Ctrl+Alt+X')
  await page.getByTestId('shortcut-pause').fill('Ctrl+Alt+P')
  await page.getByTestId('shortcuts-save').click()
  await expect(page.getByTestId('toast')).toContainText('Atalhos guardados')
  await page.getByTestId('nav-record').click()
  await expect(page.getByTestId('record-start')).toBeEnabled()
  await page.locator('details').filter({ has: page.getByTestId('retake-shortcut') }).locator('summary').click()
  await page.getByTestId('retake-shortcut').selectOption('Ctrl+Alt+X')
  await expect(page.getByTestId('record-prefs-error')).toContainText('Errei')
  await expect(page.getByTestId('retake-shortcut')).toHaveValue('Ctrl+Alt+Z')
  await expect(page.getByTestId('record-start')).toBeDisabled()
  await page.keyboard.press('Control+Alt+X')
  await expect(page.getByTestId('record-view')).toHaveAttribute('data-phase', 'idle')
  expect((await page.evaluate(() => window.tomada.record.getPrefs())).retakeShortcut).toBe('Ctrl+Alt+Z')
  await page.getByTestId('record-prefs-error').scrollIntoViewIfNeeded()
  await shot(page, 'm5-gravar-escolha-rejeitada')
  await page.getByTestId('record-prefs-use-confirmed').click()
  await expect(page.getByTestId('record-prefs-error')).toHaveCount(0)
  await expect(page.getByTestId('record-start')).toBeEnabled()

  // Retarda só a resposta de persistência: o renderer segue pelo IPC real, sem iniciar captura.
  const confirmed = await page.evaluate(() => window.tomada.record.getPrefs())
  await s.app.evaluate(({ ipcMain }, initial) => {
    let saved = initial
    ipcMain.removeHandler('record:prefs-set')
    ipcMain.handle('record:prefs-set', async (_event, patch: Partial<typeof initial>): Promise<{ ok: true; value: typeof initial }> => {
      await new Promise((resolve) => setTimeout(resolve, 1000))
      saved = { ...saved, ...patch }
      return { ok: true, value: saved }
    })
  }, confirmed)
  await page.getByTestId('fps-60').click()
  await expect(page.getByTestId('record-prefs-saving')).toBeVisible()
  await expect(page.getByTestId('record-start')).toBeDisabled()
  await page.keyboard.press('Control+Alt+X')
  await expect(page.getByTestId('record-view')).toHaveAttribute('data-phase', 'idle')
  await expect(page.getByTestId('record-prefs-saving')).toHaveCount(0)
  await expect(page.getByTestId('record-prefs-error')).toHaveCount(0)
  await expect(page.getByTestId('record-start')).toBeEnabled()
  await expect(page.getByTestId('fps-60')).toHaveAttribute('aria-pressed', 'true')
})
